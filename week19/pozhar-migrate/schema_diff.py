"""
schema_diff.py - compares two Postgres schemas and generates the SQL that turns
schema A into schema B. This is the stretch goal of mini_migrate: auto-generating a
migration instead of writing it by hand.

    introspect(conn)   reads the structure of one database
    diff(a, b)         the SQL statements that turn A into B
    render_sql(...)    those statements as text

What it understands: tables, columns (type, NOT NULL, default, SERIAL, identity,
generated), primary key / unique / foreign key / check constraints, and indexes.
What it does NOT understand: renames (a renamed column looks like a drop plus an add,
which would lose its data), views, functions, triggers, enums and other custom types,
sequences on their own, permissions, and column order. Always read the output before
running it.
"""

import re

SKIP_TABLES = {"schema_migrations"}  # the tool's own bookkeeping table is never part of a diff
SERIAL_TYPES = {"integer": "SERIAL", "bigint": "BIGSERIAL", "smallint": "SMALLSERIAL"}
NEXTVAL_RE = re.compile(r"^nextval\('.*'::regclass\)$", re.IGNORECASE)

COLUMNS_SQL = """
SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
       pg_get_expr(d.adbin, d.adrelid), a.attidentity, a.attgenerated
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
WHERE n.nspname = %s AND c.relkind = 'r'
ORDER BY c.relname, a.attnum
"""

CONSTRAINTS_SQL = """
SELECT c.relname, con.conname, con.contype, pg_get_constraintdef(con.oid)
FROM pg_constraint con
JOIN pg_class c ON c.oid = con.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = %s AND c.relkind = 'r' AND con.contype IN ('p', 'u', 'f', 'c')
ORDER BY c.relname, con.conname
"""

# indexes that are not simply the machinery behind a primary key or unique constraint
INDEXES_SQL = """
SELECT t.relname, i.relname, pg_get_indexdef(i.oid)
FROM pg_index x
JOIN pg_class i ON i.oid = x.indexrelid
JOIN pg_class t ON t.oid = x.indrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
WHERE n.nspname = %s AND t.relkind = 'r'
  AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.oid AND con.contype IN ('p', 'u'))
ORDER BY t.relname, i.relname
"""


def q(name):
    """Quotes an identifier, so unusual names (spaces, capitals, keywords) are safe."""
    return '"' + name.replace('"', '""') + '"'


# ---------------------------------------------------------------- reading a schema

def introspect(conn, schema="public"):
    """{'tables': {name: {'columns': [...], 'constraints': {name: {...}}, 'indexes': {name: sql}}}}"""
    tables = {}
    with conn.cursor() as cur:
        cur.execute(COLUMNS_SQL, (schema,))
        for table, name, type_, notnull, default, identity, generated in cur.fetchall():
            if table in SKIP_TABLES:
                continue
            t = tables.setdefault(table, {"columns": [], "constraints": {}, "indexes": {}})
            t["columns"].append({"name": name, "type": type_, "notnull": notnull, "default": default,
                                 "identity": identity, "generated": generated})
        cur.execute(CONSTRAINTS_SQL, (schema,))
        for table, name, kind, definition in cur.fetchall():
            if table in tables:
                tables[table]["constraints"][name] = {"type": kind, "def": definition}
        cur.execute(INDEXES_SQL, (schema,))
        for table, name, definition in cur.fetchall():
            if table in tables:
                tables[table]["indexes"][name] = definition
    conn.commit()
    return {"tables": tables}


# ---------------------------------------------------------------- generating SQL

def serial_type(col):
    """SERIAL/BIGSERIAL/SMALLSERIAL if this column is a classic auto-numbered one, else None."""
    if col["default"] and NEXTVAL_RE.match(col["default"]) and not col["identity"]:
        return SERIAL_TYPES.get(col["type"])
    return None


def comparable_default(col):
    """Two serial columns are 'the same default' even if their sequences are named differently."""
    return "<serial>" if serial_type(col) else col["default"]


def column_sql(col):
    parts = [q(col["name"])]
    serial = serial_type(col)
    if serial:
        parts.append(serial)
    else:
        parts.append(col["type"])
        if col["identity"]:
            parts.append("GENERATED ALWAYS AS IDENTITY" if col["identity"] == "a" else "GENERATED BY DEFAULT AS IDENTITY")
        elif col["generated"] == "s":
            parts.append(f"GENERATED ALWAYS AS ({col['default']}) STORED")
        elif col["default"] is not None:
            parts.append(f"DEFAULT {col['default']}")
    if col["notnull"] and not col["identity"]:
        parts.append("NOT NULL")
    return " ".join(parts)


def add_constraint_sql(table, name, constraint):
    return f"ALTER TABLE {q(table)} ADD CONSTRAINT {q(name)} {constraint['def']};"


def drop_constraint_sql(table, name):
    return f"ALTER TABLE {q(table)} DROP CONSTRAINT IF EXISTS {q(name)};"


def diff(a, b):
    """The SQL statements that turn schema A into schema B (in a safe order), or [] if they match."""
    ta, tb = a["tables"], b["tables"]
    drop_constraints, drop_indexes, creates, alters = [], [], [], []
    add_constraints, add_indexes, drop_columns, drop_tables = [], [], [], []

    for t in sorted(set(tb) - set(ta)):                                   # tables only in B: create them
        tbl = tb[t]
        body = [column_sql(c) for c in tbl["columns"]]
        body += [f"CONSTRAINT {q(n)} {c['def']}" for n, c in sorted(tbl["constraints"].items()) if c["type"] == "p"]
        creates.append(f"CREATE TABLE {q(t)} (\n    " + ",\n    ".join(body) + "\n);")
        add_constraints += [add_constraint_sql(t, n, c) for n, c in sorted(tbl["constraints"].items()) if c["type"] != "p"]
        add_indexes += [d + ";" for _, d in sorted(tbl["indexes"].items())]

    for t in sorted(set(ta) - set(tb)):                                   # tables only in A: drop them
        drop_constraints += [(0, drop_constraint_sql(t, n)) for n, c in sorted(ta[t]["constraints"].items())
                             if c["type"] == "f"]                          # foreign keys first, or the drop would fail
        drop_tables.append(f"DROP TABLE {q(t)};")

    for t in sorted(set(ta) & set(tb)):                                   # tables in both: compare the details
        cols_a = {c["name"]: c for c in ta[t]["columns"]}
        cols_b = {c["name"]: c for c in tb[t]["columns"]}
        for name, cb in cols_b.items():
            if name not in cols_a:
                if cb["notnull"] and cb["default"] is None and not cb["identity"] and not serial_type(cb):
                    alters.append(f"-- NOTE: {t}.{name} is NOT NULL with no default, so this fails if {t} already has rows.")
                alters.append(f"ALTER TABLE {q(t)} ADD COLUMN {column_sql(cb)};")
        for name in cols_a:
            if name not in cols_b:
                drop_columns.append(f"ALTER TABLE {q(t)} DROP COLUMN {q(name)};")
        for name, cb in cols_b.items():
            ca = cols_a.get(name)
            if ca is None:
                continue
            target = f"ALTER TABLE {q(t)} ALTER COLUMN {q(name)}"
            if ca["type"] != cb["type"]:
                alters.append(f"{target} TYPE {cb['type']} USING {q(name)}::{cb['type']};")
            if ca["notnull"] != cb["notnull"]:
                alters.append(f"{target} {'SET' if cb['notnull'] else 'DROP'} NOT NULL;")
            if (ca["identity"], ca["generated"]) != (cb["identity"], cb["generated"]):
                alters.append(f"-- NOTE: {t}.{name} changed between identity/generated/plain. Do that part by hand.")
            elif comparable_default(ca) != comparable_default(cb):
                if cb["default"] is None:
                    alters.append(f"{target} DROP DEFAULT;")
                elif serial_type(cb):
                    alters.append(f"-- NOTE: {t}.{name} became an auto-numbered column. Create its sequence by hand.")
                else:
                    alters.append(f"{target} SET DEFAULT {cb['default']};")

        con_a, con_b = ta[t]["constraints"], tb[t]["constraints"]
        for name, c in sorted(con_a.items()):
            if name not in con_b or con_b[name]["def"] != c["def"]:
                drop_constraints.append((0 if c["type"] == "f" else 1, drop_constraint_sql(t, name)))
        for name, c in sorted(con_b.items()):
            if name not in con_a or con_a[name]["def"] != c["def"]:
                add_constraints.append(add_constraint_sql(t, name, c))

        idx_a, idx_b = ta[t]["indexes"], tb[t]["indexes"]
        for name, definition in sorted(idx_a.items()):
            if name not in idx_b or idx_b[name] != definition:
                drop_indexes.append(f"DROP INDEX IF EXISTS {q(name)};")
        for name, definition in sorted(idx_b.items()):
            if name not in idx_a or idx_a[name] != definition:
                add_indexes.append(definition + ";")

    drop_constraints = [sql for _, sql in sorted(drop_constraints, key=lambda p: p[0])]
    groups = [
        ("Remove constraints that were dropped or changed", drop_constraints),
        ("Remove indexes that were dropped or changed", drop_indexes),
        ("Create new tables", creates),
        ("Add and change columns", alters),
        ("Add constraints", add_constraints),
        ("Add indexes", add_indexes),
        ("DESTRUCTIVE: drop columns (their data is lost)", drop_columns),
        ("DESTRUCTIVE: drop tables (their data is lost)", drop_tables),
    ]
    statements = []
    for title, items in groups:
        if items:
            statements.append(f"-- {title}")
            statements += items
    return statements


def render_sql(statements):
    return "\n".join(statements)
